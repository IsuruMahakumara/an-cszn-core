#!/usr/bin/env python3
"""
Rebuild universe.txt from Binance USD-M Futures REST (public).

Picks TRADING perpetual pairs quoted in USDT or USDC whose MIN_NOTIONAL is 5,
then keeps the top N by 24h quote volume.

  source python-api-tests/.venv/bin/activate
  python python-api-tests/refresh_universe.py
"""

from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path

import requests

# live public fapi — volume / filters match real market (demo is thinner)
BASE_URL = "https://fapi.binance.com"

# write next to this script (same file bar_signal_demo loads)
OUT_PATH = Path(__file__).with_name("universe.txt")

# how many symbols after filters + volume rank
TOP_N = 200
# only quotes the bot already trades
QUOTE_ASSETS = frozenset({"USDT", "USDC"})
# exchange min notional gate must be exactly this many quote units
MIN_NOTIONAL = 5.0
# float compare tolerance for filter strings like "5" / "5.0"
NOTIONAL_EPS = 1e-9


def get_json(path: str):
    # public GET — no keys
    r = requests.get(BASE_URL + path, timeout=30)
    r.raise_for_status()
    return r.json()


def notional_filter(filters: list[dict]) -> float | None:
    # MIN_NOTIONAL (legacy) or NOTIONAL (current) on USD-M
    for f in filters:
        ft = f.get("filterType")
        if ft not in ("MIN_NOTIONAL", "NOTIONAL"):
            continue
        raw = f.get("notional") or f.get("minNotional")
        if raw is None:
            continue
        return float(raw)
    return None


def eligible_symbols() -> dict[str, float]:
    """
    symbol → min notional for pairs that pass status / quote / notional checks.
    """
    info = get_json("/fapi/v1/exchangeInfo")
    out: dict[str, float] = {}
    for s in info.get("symbols") or []:
        # live trading only
        if s.get("status") != "TRADING":
            continue
        # perpetuals only (drop dated delivery contracts)
        if s.get("contractType") != "PERPETUAL":
            continue
        # USDT- and USDC-quoted both OK
        if s.get("quoteAsset") not in QUOTE_ASSETS:
            continue
        mn = notional_filter(s.get("filters") or [])
        if mn is None:
            continue
        # strict: min notional == 5 in quote
        if abs(mn - MIN_NOTIONAL) > NOTIONAL_EPS:
            continue
        out[s["symbol"]] = mn
    return out


def quote_volumes() -> dict[str, float]:
    # 24h ticker array — rank by notional volume in quote asset
    tickers = get_json("/fapi/v1/ticker/24hr")
    vols: dict[str, float] = {}
    for t in tickers:
        sym = t.get("symbol")
        if not sym:
            continue
        vols[sym] = float(t.get("quoteVolume") or 0)
    return vols


def top_symbols(eligible: dict[str, float], volumes: dict[str, float], n: int) -> list[str]:
    # only symbols that pass filters AND have a 24h ticker
    ranked = sorted(
        (sym for sym in eligible if sym in volumes),
        key=lambda s: volumes[s],
        reverse=True,
    )
    return ranked[:n]


def write_universe(path: Path, symbols: list[str]) -> None:
    # UTC stamp so the file is self-describing after regeneration
    ts = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    lines = [
        "# Explicit USD-M Futures universe — one symbol per line (# = comment).",
        "# USDT- and USDC-quoted pairs both OK (e.g. BTCUSDT, BNBUSDC).",
        f"# auto-generated by refresh_universe.py @ {ts}",
        f"# top {len(symbols)} by 24h quoteVolume · minNotional={MIN_NOTIONAL} · {BASE_URL}",
        "",
    ]
    for sym in symbols:
        # pure symbol lines — bar_signal_demo ignores # comments only
        lines.append(sym)
    lines.append("")
    path.write_text("\n".join(lines))


def main() -> None:
    print(f"fetch exchangeInfo from {BASE_URL} …")
    eligible = eligible_symbols()
    print(f"  eligible (perp · USDT/USDC · minNotional={MIN_NOTIONAL}): {len(eligible)}")

    print("fetch 24h tickers …")
    volumes = quote_volumes()
    print(f"  ticker rows: {len(volumes)}")

    symbols = top_symbols(eligible, volumes, TOP_N)
    if not symbols:
        raise SystemExit("no symbols matched — check filter / API response")

    write_universe(OUT_PATH, symbols)
    # short proof line: rank-1 volume vs rank-last
    top_v = volumes[symbols[0]]
    bot_v = volumes[symbols[-1]]
    print(
        f"wrote {OUT_PATH}  n={len(symbols)}  "
        f"#{1} {symbols[0]} quoteVol={top_v:,.0f}  "
        f"#{len(symbols)} {symbols[-1]} quoteVol={bot_v:,.0f}"
    )


if __name__ == "__main__":
    main()
